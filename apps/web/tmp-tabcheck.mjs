import { chromium } from '@playwright/test';
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
await page.goto('http://localhost:3000/login');
await page.fill('input[type="email"], input[name="email"]', 'admin@rpa.studio');
await page.fill('input[type="password"]', 'secret123');
await page.click('button[type="submit"]');
await page.waitForURL(/\/recipes/);
await page.goto('http://localhost:3000/recipes/01a16acc-aa68-72a6-9c04-1c2d61c5b224/edit');
await page.waitForSelector('.react-flow', { timeout: 30000 });
await page.waitForTimeout(3000);
await page.locator('.react-flow__node').nth(1).dblclick();
await page.waitForSelector('[role="dialog"][aria-modal="true"]');
await page.waitForTimeout(1200);
const dialog = page.locator('[role="dialog"][aria-modal="true"]');
const activeCenter = () => dialog.locator('[role="tab"][aria-selected="true"]').first().textContent();
await dialog.getByRole('tab', { name: 'Ajustes' }).click();
await page.waitForTimeout(600);
console.log('center before exec:', (await activeCenter())?.trim());
await page.keyboard.press('Control+Enter');
await page.waitForTimeout(2500);
console.log('center after exec:', (await activeCenter())?.trim());
console.log('right tab selected:', (await dialog.getByRole('tab', { name: 'Salida' }).getAttribute('aria-selected')));
await page.waitForTimeout(600);
await page.screenshot({ path: '/tmp/opencode/after-exec-crisp.png' });
await browser.close();
